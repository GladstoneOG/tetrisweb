export const SPAWN_COLUMN: Record<TetrominoType, number> = {
  I: 3,
  O: 3,
  T: 3,
  S: 3,
  Z: 3,
  J: 3,
  L: 3,
};

export function getPieceCells(
  type: TetrominoType,
  rotation: RotationState,
  x: number,
  y: number
): GridPoint[] {
  return TETROMINO_SHAPES[type][rotation].map((offset) => ({
    x: x + offset.x,
    y: y + offset.y,
  }));
}

export function getPieceColor(type: TetrominoType): string {
  return TETROMINO_COLORS[type];
}

export interface TightPieceShape {
  type: TetrominoType;
  color: string;
  width: number;
  height: number;
  cells: GridPoint[];
}

/**
 * Returns tight-cropped local cell coordinates (origin at 0,0) for mini previews
 * such as Hold and Next queue canvases.
 */
export function getTightPieceShape(
  type: TetrominoType,
  rotation: RotationState = 0
): TightPieceShape {
  const raw = TETROMINO_SHAPES[type][rotation];
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const pt of raw) {
    if (pt.x < minX) minX = pt.x;
    if (pt.y < minY) minY = pt.y;
    if (pt.x > maxX) maxX = pt.x;
    if (pt.y > maxY) maxY = pt.y;
  }

  return {
    type,
    color: TETROMINO_COLORS[type],
    width: maxX - minX + 1,
    height: maxY - minY + 1,
    cells: raw.map((pt) => ({ x: pt.x - minX, y: pt.y - minY })),
  };
}
